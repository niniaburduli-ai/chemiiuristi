export async function getHomePage(): Promise<HomePageData | null> {
  try {
    await dbConnect()
    const doc = await HomePage.findOne({ status: "published", locale: { $ne: "en" } }).lean()
    if (!doc) return null
    const data = toPlain(doc as unknown as HomePageData)
    if (data.pricingHeading === INFORMAL_PRICING) {
      data.pricingHeading = HOME_SEED.pricingHeading
    }
    if (data.serviceCards?.length) {
      data.serviceCards = data.serviceCards.map((card) => ({
        ...card,
        subtitle:  INFORMAL_CARD_SUBTITLES[card.subtitle]  ?? card.subtitle,
        ctaText:   INFORMAL_CARD_CTA[card.ctaText ?? ""]   ?? card.ctaText,
        // Pre-launch "Documents" card pointed at the placeholder /docs route;
        // it's now the document analysis modal trigger.
        // Pre-launch "Templates" card pointed at the placeholder /templates route,
        // which never existed; the feature lives at /generate.
        href:
          card.href === "/docs" ? "/review" :
          card.href === "/templates" ? "/generate" :
          card.href,
        comingSoon: card.href === "/docs" || card.href === "/templates" ? false : card.comingSoon,
      }))
    }
    return data
  } catch { return null }
}

