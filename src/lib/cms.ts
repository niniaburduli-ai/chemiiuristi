    await dbConnect()
    const doc = locale === "en"
      ? await SiteConfig.findOne({ locale: "en" }).lean()
      : await SiteConfig.findOne({ locale: { $ne: "en" } }).lean() ?? await SiteConfig.findOne().lean()
